"""Orchestration: read every export, build one inventory, write one workbook."""

import os
from typing import Dict, List, Optional

import pandas as pd

from . import analyze, build, diagram, export, loaders, schema
from .config import DEFAULT_OUTPUT_NAME, DEFAULT_SOURCE_DIR


class InventoryAgent:
    """Reads the US Ad Sales MicroStrategy exports and produces a single master inventory."""

    def __init__(self, source_dir: str = DEFAULT_SOURCE_DIR,
                 output_path: Optional[str] = None, verbose: bool = True):
        self.source_dir = source_dir
        self.output_path = output_path or os.path.join(source_dir, DEFAULT_OUTPUT_NAME)
        self.verbose = verbose
        self.frames: Dict[str, pd.DataFrame] = {}
        self.provenance: List[dict] = []
        self.master = pd.DataFrame()
        self.sheets: Dict[str, pd.DataFrame] = {}
        self.artifacts: List[str] = []

    def log(self, msg: str):
        if self.verbose:
            print(msg, flush=True)

    def run(self) -> str:
        self.log(f"Source directory: {self.source_dir}")

        self.log("Reading exports...")
        self.frames, self.provenance = loaders.load_all(self.source_dir)
        for p in self.provenance:
            self.log(f"   {p['Source File']:<42} {p['Rows Read']:>6,} rows")

        self.log("Building master inventory (IDs, descriptions, classification)...")
        self.master = build.build_master(self.frames)
        self.log(f"   {len(self.master):,} objects catalogued")

        self.log("Running analysis...")
        self.sheets = self._assemble_sheets()

        self.log(f"Writing workbook: {self.output_path}")
        export.write_workbook(self.output_path, self.sheets, self._read_me())

        self._write_schema_artifacts()
        self.log("Done.")
        return self.output_path

    def _write_schema_artifacts(self):
        """Mermaid ER diagrams and the bus-matrix image sit alongside the workbook."""
        out_dir = os.path.dirname(os.path.abspath(self.output_path))
        stem = os.path.splitext(os.path.basename(self.output_path))[0]

        mmd = diagram.write_mermaid(
            os.path.join(out_dir, f"{stem}_Schema.md"),
            self.sheets.get("Fact-Dimension Edges", pd.DataFrame()),
            self.sheets.get("Star Schema Map", pd.DataFrame()),
        )
        png = diagram.write_bus_matrix_image(
            os.path.join(out_dir, f"{stem}_BusMatrix.png"),
            self.sheets.get("Fact-Dimension Edges", pd.DataFrame()),
        )
        for art in (mmd, png):
            if art:
                self.artifacts.append(art)
                self.log(f"   wrote {os.path.basename(art)}")

    def _assemble_sheets(self) -> Dict[str, pd.DataFrame]:
        m = self.master
        draft = loaders.load_draft_sheets(self.source_dir)

        edges = schema.fact_dimension_edges(draft, m)
        star = schema.star_schema_map(edges, draft)
        conformance = schema.dimension_conformance(edges, m)
        attr_map = schema.attribute_table_map(m)

        sheets: Dict[str, pd.DataFrame] = {
            "Summary": analyze.summary(m, self.provenance),
            "Master Inventory": m,
            "Reports & Dashboards": _slice(m, "Report"),
            "Dashboard Register": analyze.dashboard_register(m),
            "Attributes": _slice(m, "Attribute"),
            "Metrics": _slice(m, "Metric"),
            "Filters": _slice(m, "Filter"),
            "Tables": _slice(m, "Table"),
            "Database Instances": _slice(m, "Database Instance"),
            "Database Connections": _slice(m, "Database Connection"),
            "Report Object Links": analyze.report_object_links(m),
            "Business Area Coverage": analyze.business_area_coverage(m),
            "Personal Folder Footprint": analyze.owner_footprint(m),
            "Duplicate Names": analyze.duplicate_names(m),
            "Data Quality Issues": analyze.data_quality(m),
            "Source Provenance": pd.DataFrame(self.provenance),

            # --- schema view ---
            "Schema Overview": schema.schema_overview(m, edges, conformance, attr_map),
            "Table Register": schema.table_register(m, edges),
            "Star Schema Map": star,
            "Fact-Dimension Edges": edges,
            "Dimension Conformance": conformance,
            "Attribute to Table Map": attr_map,
        }
        # Fact/dimension analysis exists only in the earlier hand-built draft; carry it forward.
        for name, df in draft.items():
            sheets[name] = df
        return sheets

    def _read_me(self) -> List[str]:
        n = len(self.master)
        reports = int((self.master["Object Type"] == "Report").sum())
        dash = int((self.master["Deliverable Class"] == "Dashboard").sum())
        return [
            f"Generated by the MSTR Inventory Agent from {len(self.provenance)} MicroStrategy "
            f"exports in: {self.source_dir}",
            "",
            f"This workbook consolidates {n:,} objects — {reports:,} report objects "
            f"(of which {dash:,} are dashboard-class), plus attributes, metrics, filters, "
            "warehouse tables, database instances and database connections — into one "
            "inventory with a single identifier scheme.",
            "",
            "HOW OBJECTS ARE IDENTIFIED:",
            "  * The supplied exports contain NO MicroStrategy GUIDs. 'Object ID' and "
            "'Surrogate GUID' are therefore generated by the agent.",
            "  * They are deterministic: a SHA-256 of object type + folder path + name. The same "
            "export always yields the same IDs, so the inventory can be re-generated and diffed.",
            "  * 'Object ID' is the short quotable form (e.g. RPT-1A2B3C4D5E6F). 'Surrogate GUID' "
            "is the 32-character MSTR-shaped form.",
            "  * 'MSTR GUID' is deliberately left EMPTY. Populate it from an MSTR Command Manager "
            "or Enterprise Manager extract to bind this inventory to the real repository.",
            "  * Because IDs are path-derived, moving or renaming an object changes its ID. Bind "
            "real GUIDs before using these IDs as long-term keys.",
            "",
            "HOW DESCRIPTIONS ARE PRODUCED:",
            "  * The exports contain no description field, so descriptions are DERIVED by the "
            "agent from each object's name, type and folder taxonomy plus an ad-sales glossary.",
            "  * The 'Description Source' column states this per row. Treat derived text as a "
            "steward's starting point, not as authoritative documentation.",
            "",
            "KNOWN GAPS IN THE SOURCE DATA (not solvable from these files):",
            "  * No report definitions, so true report-to-metric/attribute/filter dependencies "
            "cannot be resolved. 'Report Object Links' contains only evidence-backed links where "
            "an object physically sits inside a report's folder.",
            "  * No MSTR document/dossier export was supplied, so dashboards are identified by "
            "folder and naming convention rather than by object type.",
            "  * No usage statistics (hit counts, last-run dates), so 'in use' cannot be "
            "determined. An Enterprise Manager extract would close this and the two gaps above.",
            "",
            "SHEET GUIDE:",
            "  Summary                   Counts and coverage across the whole inventory",
            "  Master Inventory          Every object, one row each, unified column contract",
            "  Reports & Dashboards      Report objects only, with class and business area",
            "  Dashboard Register        Dashboard-class deliverables and their component reports",
            "  Attributes / Metrics / Filters / Tables     Building blocks by type",
            "  Database Instances / Connections            Data source configuration",
            "  Report Object Links       Evidence-backed report-to-object links",
            "  Business Area Coverage    Object type counts per business area",
            "  Personal Folder Footprint Ungoverned content by user",
            "  Duplicate Names           Every repeated object name, with shared/personal split",
            "  Data Quality Issues       Duplicates, orphans, ownership and naming problems",
            "  Source Provenance         Which file each row came from, with row counts",
            "",
            "SCHEMA VIEW SHEETS:",
            "  Schema Overview           Table counts, star coverage and stated limitations",
            "  Table Register            All warehouse tables with their star-schema role",
            "  Star Schema Map           One row per fact: grain, dimension count, conformance",
            "  Fact-Dimension Edges      Normalised fact-to-dimension join list",
            "  Dimension Conformance     Which dimensions are shared, private or unlinked",
            "  Attribute to Table Map    Inferred attribute lineage, graded by confidence",
            "  Fact-Dimension Join Map / Fact x Dim Matrix   Carried forward from the prior draft",
            "",
            "SCHEMA VIEW CAVEAT: the exports list table NAMES only — no columns, data types, "
            "primary/foreign keys or join expressions. The schema sheets are therefore a "
            "LOGICAL star-schema view inferred from naming conventions and the validated "
            "fact/dimension analysis, not an extract of the physical warehouse schema. "
            "Attribute-to-table lineage is inferred by name matching and is graded High/Medium/"
            "Low so it is not mistaken for verified lineage.",
        ]


def _slice(master: pd.DataFrame, object_type: str) -> pd.DataFrame:
    df = master[master["Object Type"] == object_type].copy()
    df = df.drop(columns=[c for c in df.columns if df[c].isna().all() and c != "MSTR GUID"])
    return df.reset_index(drop=True)
