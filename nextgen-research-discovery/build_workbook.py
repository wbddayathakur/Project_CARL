def classify_measure(name):
    for rx, fam, base, src, definition, cube in K.MEASURE_RULES:
        if re.search(rx, name):
            variant = next((label for vrx, label in K.VARIANTS if re.search(vrx, name)), "Base")
            return fam, base, src, definition, variant, cube
    return "Unclassified", "*MEASURES", "?", "Not inferable from name - read DAX", "Base", "TBC"


# fact tables reached through measures (they are never placed on visuals directly)
fact_pages_via_measures = collections.defaultdict(set)
for m in measures:
    fam, base, *_ = classify_measure(m["field"])
    for t in re.findall(r"[A-Z][A-Z0-9_]+(?:_[A-Z0-9]+)*", base):
        if t in K.TABLES:
            fact_pages_via_measures[t].update(m["pages"])


def pages_for(table):
    pg = set(pages_by_table.get(table, set())) | fact_pages_via_measures.get(table, set())
    pg.discard("(report-level filter)")
    return sorted(pg)


def visible_count(pages):
    return sum(1 for p in pages if not page_hidden.get(p, True))


