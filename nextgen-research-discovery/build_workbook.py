    erd_current = ["erDiagram"]
    seen = set()
    for g, tables in groups.items():
        if not tables:
            continue
        fact = next((t for t in tables if K.TABLES.get(t, ("",))[0].startswith("Fact")), tables[0])
        for d in [t for t in tables if t != fact]:
            if K.TABLES.get(d, ("",))[0] in ("Fact", "Fact / flag") and d != fact:
                rel = f"    {mid(d)} }}o--o{{ {mid(fact)} : \"same subject\""
            else:
                rel = f"    {mid(d)} ||--o{{ {mid(fact)} : \"filters\""
            if rel not in seen:
                seen.add(rel)
